#!/usr/bin/env python3
"""Builds the Arduino IDE copy of the firmware: arduino/arm_firmware/.

The PlatformIO project (src/ and lib/arm_core/) is the code we edit. Arduino IDE wants every
file of a sketch in one folder, so this copies them there, flat, with:
  arm_firmware.ino  empty except for comments (setup() and loop() are in main.cpp)
  build_opt.h       compiler flags Arduino IDE has no menu for (the 12 MHz crystal)

Run it after changing the firmware, and commit the result:
  python3 tools/make_arduino_sketch.py           write the sketch
  python3 tools/make_arduino_sketch.py --check   fail if the sketch is out of date
"""

import argparse
import sys
from pathlib import Path

FIRMWARE = Path(__file__).resolve().parent.parent
SOURCES = [FIRMWARE / 'lib' / 'arm_core' / 'src', FIRMWARE / 'src']  # src/sim/ is not copied
SKETCH = FIRMWARE / 'arduino' / 'arm_firmware'

BANNER = ('// GENERATED by firmware/tools/make_arduino_sketch.py from firmware/{src}.\n'
          '// Do not edit here: change the original and run the script again.\n\n')

INO = """\
// Arm firmware for the BigTreeTech Octopus (STM32F446ZE), Arduino IDE copy.
// GENERATED by firmware/tools/make_arduino_sketch.py. Do not edit: change firmware/src/
// or firmware/lib/arm_core/ and run the script again.
//
// setup() and loop() are in main.cpp. How to build and flash: README.md in this folder.
"""

# Read by STM32duino's platform.txt and passed to the compiler.
BUILD_OPT = '-DHSE_VALUE=12000000U\n'

README = """\
# Arm firmware: Arduino IDE copy

GENERATED by `firmware/tools/make_arduino_sketch.py`. Do not edit these files: change
`firmware/src/` or `firmware/lib/arm_core/` and run the script again.

## One-time setup

1. Arduino IDE: File > Preferences > Additional boards manager URLs, add
   `https://github.com/stm32duino/BoardManagerFiles/raw/main/package_stmicroelectronics_index.json`
2. Boards Manager: install **STM32 MCU based boards** (by STMicroelectronics).
3. Library Manager: install **TMCStepper** (by teemuatlut), version 0.7.3.
4. Install **STM32CubeProgrammer** (Arduino IDE calls it to flash).

## Tools menu

| Setting | Value |
|---|---|
| Board | STM32 MCU based boards > Generic STM32F4 series |
| Board part number | Generic F446ZETx |
| USB support | CDC (generic 'Serial' supersede U(S)ART) |
| Upload method | STM32CubeProgrammer (DFU), or (SWD) with an ST-Link |

The build stops with an error if the board or USB setting is wrong.

## Flashing over USB (DFU)

1. Motor power off. Fit the BOOT0 jumper, connect USB-C, press reset.
2. Sketch > Upload.
3. Remove the BOOT0 jumper and press reset.

This replaces BTT's SD-card bootloader; the firmware starts at 0x08000000.

## Check it

Serial monitor, any baud rate, line ending Newline: `INFO` should print `sysclk=180000000`
(and later, after a fast move, a `tick_max` well under `tick_budget`).
Turn motor power on, then `DRIVERS` should list every driver as `ok`. `HELP` lists the rest.
"""


def expected_files():
    files = {'arm_firmware.ino': INO, 'build_opt.h': BUILD_OPT, 'README.md': README}
    for folder in SOURCES:
        for path in sorted(folder.iterdir()):
            if path.suffix not in ('.h', '.cpp'):
                continue
            if path.name in files:
                sys.exit(f'two files named {path.name}: the sketch folder is flat')
            src = path.relative_to(FIRMWARE)
            files[path.name] = BANNER.format(src=src) + path.read_text()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true',
                        help='only check that the sketch matches the sources')
    args = parser.parse_args()

    files = expected_files()
    existing = {p.name for p in SKETCH.glob('*')} if SKETCH.exists() else set()
    stale = sorted(name for name, text in files.items()
                   if not (SKETCH / name).exists() or (SKETCH / name).read_text() != text)
    extra = sorted(existing - set(files))

    if args.check:
        if stale or extra:
            print('Arduino sketch is out of date (run tools/make_arduino_sketch.py):',
                  ', '.join(stale + extra))
            return 1
        print('Arduino sketch is up to date.')
        return 0

    SKETCH.mkdir(parents=True, exist_ok=True)
    for name in extra:
        (SKETCH / name).unlink()
    for name in stale:
        (SKETCH / name).write_text(files[name])
    print(f'Wrote {SKETCH.relative_to(FIRMWARE)}/ ({len(stale)} changed, {len(extra)} removed)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
